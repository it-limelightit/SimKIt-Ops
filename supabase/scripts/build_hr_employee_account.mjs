import { build } from "esbuild";
import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = fileURLToPath(new URL("../../", import.meta.url));
const output = path.join(root, "supabase/dashboard-deploy");
await mkdir(output, { recursive: true });
const result = await build({
  entryPoints: [path.join(root, "supabase/functions/hr-employee-account/index.ts")],
  bundle: true,
  write: false,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  external: ["https://*"],
  banner: {
    js: "// Generated by supabase/scripts/build_hr_employee_account.mjs. Edit the source function, then regenerate.\n// Deploy as hr-employee-account with gateway Verify JWT disabled; session and HR authorization are checked inside the handler.",
  },
});
const source = result.outputFiles[0].text;
if (/from\s+["']\.\.?\//.test(source)) throw new Error("HR function contains an unresolved local import");
await writeFile(path.join(output, "hr-employee-account.ts"), source);
console.log("Prepared self-contained HR employee account function for Supabase deployment.");
